//! The whole-project check (spec 0009 R1, R3): everything wrong with a
//! project directory, as findings, without writing a byte. It reads each
//! source file on its own first, so one broken file is reported with its
//! position instead of ending the run, then loads the project through the
//! same reader the editor uses and adds what that reader reports.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use crate::error::{FormatError, Result};

use fanta_doc::{AssetId, Doc, NodeData, NodeId};
use serde_json::Value;

use super::diagnostic::{
    DESIGN_UNAVAILABLE, ID_DUPLICATE, LOAD_FAILED, MANIFEST_FILE_MISSING, PARSE_CONFLICT_MARKER, PARSE_CSS,
    PARSE_JSON, PARSE_SVG, RECORD_NO_ELEMENT, REF_MISSING_ASSET, REF_MISSING_COMPONENT,
    SourceDiagnostic, SourceSeverity,
};
use super::layout::{ASSETS_DIR, COMPONENTS_DIR, DOC_DIR, FANTA_JSON, PAGES_DIR, json_key};
use super::read::read_project_tree_with_warnings;
use super::web::{DESIGN_CSS, asset_hrefs, web_project_files};
use super::web_read::first_attributes;

const NODES_JSON: &str = "nodes.json";
const ASSET_INDEX: &str = "assets/index.json";

/// Check the project at `dir`. `Err` only when `dir` is not a project at all
/// or cannot be read; every problem inside a project is a finding. Findings
/// are sorted by file, position and code.
pub fn check_project(dir: &Path) -> Result<Vec<SourceDiagnostic>> {
    if !dir.join(FANTA_JSON).is_file() {
        return Err(FormatError::NotAProject {
            path: dir.to_path_buf(),
        });
    }
    let mut findings = Vec::new();
    let files = source_files(dir)?;
    // Design SVG text by name, to say where a node's element is.
    let mut svgs = BTreeMap::new();
    for (name, path) in &files {
        // Assets and anything else that is not text have nothing to parse.
        let Ok(text) = fs::read_to_string(path) else {
            continue;
        };
        check_file(name, &text, &mut findings);
        if name == ASSET_INDEX {
            check_asset_index(dir, &text, &mut findings);
        }
        if name.ends_with(".svg") {
            svgs.insert(name.clone(), text);
        }
    }
    check_design_records(dir, &files, &mut findings);

    let broken = findings
        .iter()
        .any(|finding| finding.severity == SourceSeverity::Error);
    match read_project_tree_with_warnings(dir) {
        Ok((doc, assets, warnings)) => {
            // After a file error the loader's own reports are its echoes
            // (a conflict marker read as a declaration), so they would only
            // bury the cause.
            if !broken {
                findings.extend(warnings);
            }
            check_references(&doc, &assets, &svgs, &mut findings)?;
            if !broken {
                check_projection(dir, &doc, &assets, &svgs, &mut findings)?;
            }
        }
        // A load that fails after a file error is that error's consequence.
        Err(_) if broken => {}
        Err(error) => findings.push(SourceDiagnostic::error(
            LOAD_FAILED,
            format!("the project does not load: {error}"),
        )),
    }

    findings.sort_by(|a, b| {
        (&a.file, a.line, a.column, a.code, &a.node_id, &a.message).cmp(&(
            &b.file,
            b.line,
            b.column,
            b.code,
            &b.node_id,
            &b.message,
        ))
    });
    findings.dedup();
    Ok(findings)
}

/// The files a load reads, as (project-relative name, path), in name order.
/// Derived files (`map.json`, `tokens.css`, the viewer) are regenerated by
/// every save, so damage to them is not a finding.
/// Findings as the JSON `fanta-check --json` prints. The MCP servers return
/// the same text (spec 0009 A6).
pub fn findings_json(findings: &[SourceDiagnostic]) -> Result<String> {
    Ok(serde_json::to_string_pretty(findings)?)
}

/// The page and component directories holding a file that does not parse,
/// with the findings that say why (spec 0009 R11). The collecting load leaves
/// these designs out; it uses this pass so the editor and `fanta-check` agree
/// on what "does not parse" means.
// shortcut: reads every design file a second time on open; fold into the
// loader's own parse if open time on large projects shows it.
pub(crate) fn unparsable_designs(dir: &Path) -> Result<(BTreeSet<PathBuf>, Vec<SourceDiagnostic>)> {
    let mut unavailable = BTreeSet::new();
    let mut findings = Vec::new();
    let files = source_files(dir)?;
    // A design whose records file is gone cannot be read either.
    let mut without_records = Vec::new();
    check_design_records(dir, &files, &mut without_records);
    for finding in without_records {
        let Some(design_name) = finding
            .file
            .as_deref()
            .and_then(|file| file.strip_suffix("/nodes.json"))
            .map(str::to_owned)
        else {
            continue;
        };
        findings.push(finding);
        if unavailable.insert(dir.join(&design_name)) {
            findings.push(design_unavailable(&design_name));
        }
    }
    for (name, path) in files {
        if !(name.starts_with(PAGES_DIR) || name.starts_with(COMPONENTS_DIR)) {
            continue;
        }
        let Ok(text) = fs::read_to_string(&path) else {
            continue;
        };
        let mut found = Vec::new();
        check_file(&name, &text, &mut found);
        found.retain(|finding| finding.code.starts_with("parse."));
        let (Some(design), Some((design_name, file))) = (path.parent(), name.rsplit_once('/'))
        else {
            continue;
        };
        // Only the files a design cannot be read without. A damaged id
        // sidecar of a legacy project, for one, is rebuilt on load.
        let needed = matches!(
            file,
            "page.json" | "def.json" | "nodes.json" | "page.svg" | "page.css" | "master.svg" | "master.css"
        );
        if found.is_empty() || !needed {
            continue;
        }
        findings.extend(found);
        if unavailable.insert(design.to_path_buf()) {
            findings.push(design_unavailable(design_name));
        }
    }
    Ok((unavailable, findings))
}

fn design_unavailable(design_name: &str) -> SourceDiagnostic {
    SourceDiagnostic::error(
        DESIGN_UNAVAILABLE,
        format!(
            "{design_name} is not loaded because a file in it is missing or does not parse; saving leaves its files as they are"
        ),
    )
    .in_file(design_name)
}

fn source_files(dir: &Path) -> Result<Vec<(String, PathBuf)>> {
    let mut found = BTreeMap::new();
    for name in [FANTA_JSON, DESIGN_CSS] {
        let path = dir.join(name);
        if path.is_file() {
            found.insert(name.to_owned(), path);
        }
    }
    for root in [DOC_DIR, PAGES_DIR, COMPONENTS_DIR, ASSETS_DIR] {
        let mut pending = vec![dir.join(root)];
        while let Some(folder) = pending.pop() {
            let entries = match fs::read_dir(&folder) {
                Ok(entries) => entries,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
                Err(error) => return Err(error.into()),
            };
            for entry in entries {
                let path = entry?.path();
                if path.is_dir() {
                    pending.push(path);
                    continue;
                }
                let checked = matches!(
                    path.extension().and_then(|extension| extension.to_str()),
                    Some("json" | "svg" | "css")
                ) && path.file_name().is_some_and(|file| file != "map.json");
                if checked && let Ok(relative) = path.strip_prefix(dir) {
                    let name = relative.to_string_lossy().replace('\\', "/");
                    found.insert(name, path);
                }
            }
        }
    }
    Ok(found.into_iter().collect())
}

fn check_file(name: &str, text: &str, findings: &mut Vec<SourceDiagnostic>) {
    if let Some(offset) = conflict_marker(text) {
        findings.push(
            SourceDiagnostic::error(
                PARSE_CONFLICT_MARKER,
                format!("{name}: unresolved merge conflict; pick one side and remove the markers"),
            )
            .in_file(name)
            .at_offset(text, offset),
        );
        return;
    }
    if name.ends_with(".json") {
        if let Err(error) = serde_json::from_str::<serde::de::IgnoredAny>(text) {
            findings.push(
                SourceDiagnostic::error(PARSE_JSON, format!("{name}: not valid JSON ({error})"))
                    .in_file(name)
                    .at(error.line(), error.column()),
            );
        }
    } else if name.ends_with(".svg") {
        check_svg(name, text, findings);
    } else if name.ends_with(".css")
        && let Some((offset, problem)) = css_problem(text)
    {
        findings.push(
            SourceDiagnostic::error(PARSE_CSS, format!("{name}: {problem}"))
                .in_file(name)
                .at_offset(text, offset),
        );
    }
}

/// The offset of the first line that is a git conflict marker.
fn conflict_marker(text: &str) -> Option<usize> {
    let mut offset = 0;
    for line in text.split_inclusive('\n') {
        if line.starts_with("<<<<<<< ") || line.starts_with(">>>>>>> ") {
            return Some(offset);
        }
        offset += line.len();
    }
    None
}

/// Well-formedness and duplicate ids. The loader's own SVG pass stops at the
/// first error and keeps what came before; here that is an error, because
/// the next save would regenerate the file from the records.
fn check_svg(name: &str, text: &str, findings: &mut Vec<SourceDiagnostic>) {
    use quick_xml::events::Event;
    let mut reader = quick_xml::Reader::from_str(text);
    let mut depth = 0usize;
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut note_id = |start: &quick_xml::events::BytesStart<'_>| {
        for attribute in first_attributes(start) {
            if attribute.key.as_ref() == b"id"
                && let Ok(id) = attribute.unescape_value()
            {
                *seen.entry(id.into_owned()).or_default() += 1;
            }
        }
    };
    let problem = loop {
        match reader.read_event() {
            Ok(Event::Start(start)) => {
                depth += 1;
                note_id(&start);
            }
            Ok(Event::Empty(start)) => note_id(&start),
            Ok(Event::End(_)) => depth = depth.saturating_sub(1),
            Ok(Event::Eof) if depth > 0 => {
                break Some((text.len(), "the file ends inside an element".to_owned()));
            }
            Ok(Event::Eof) => break None,
            Err(error) => {
                let offset = usize::try_from(reader.error_position()).unwrap_or(text.len());
                break Some((offset, error.to_string()));
            }
            Ok(_) => {}
        }
    };
    if let Some((offset, problem)) = problem {
        findings.push(
            SourceDiagnostic::error(
                PARSE_SVG,
                format!("{name}: not well-formed ({problem}); a save would regenerate it from nodes.json"),
            )
            .in_file(name)
            .at_offset(text, offset),
        );
    }
    for (id, count) in seen {
        if count < 2 {
            continue;
        }
        let needle = format!("id=\"{id}\"");
        let finding = SourceDiagnostic::error(
            ID_DUPLICATE,
            format!("{name}: id {id:?} is on {count} elements; a pasted copy needs its own node"),
        )
        .in_file(name);
        findings.push(match text.match_indices(&needle).nth(1) {
            Some((offset, _)) => finding.at_offset(text, offset),
            None => finding,
        });
    }
}

/// Unbalanced braces, outside comments: the offset and what is wrong.
fn css_problem(text: &str) -> Option<(usize, &'static str)> {
    let mut open = Vec::new();
    let mut rest = text.char_indices().peekable();
    while let Some((offset, character)) = rest.next() {
        match character {
            '/' if rest.peek().is_some_and(|(_, next)| *next == '*') => {
                rest.next();
                let mut previous = ' ';
                for (_, next) in rest.by_ref() {
                    if previous == '*' && next == '/' {
                        break;
                    }
                    previous = next;
                }
            }
            '{' => open.push(offset),
            '}' if open.pop().is_none() => return Some((offset, "a } closes nothing")),
            _ => {}
        }
    }
    open.first().map(|offset| (*offset, "this { is never closed"))
}

/// Every asset the index lists has its file.
fn check_asset_index(dir: &Path, text: &str, findings: &mut Vec<SourceDiagnostic>) {
    let Ok(index) = serde_json::from_str::<Value>(text) else {
        return;
    };
    let Some(listed) = index.get("assets").and_then(Value::as_object) else {
        return;
    };
    let mut present = Vec::new();
    let mut pending = vec![dir.join(ASSETS_DIR)];
    while let Some(folder) = pending.pop() {
        for entry in fs::read_dir(&folder).into_iter().flatten().flatten() {
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
            } else if let Some(stem) = path.file_stem() {
                present.push(stem.to_string_lossy().into_owned());
            }
        }
    }
    for id in listed.keys() {
        if present.iter().any(|stem| stem == id) {
            continue;
        }
        let finding = SourceDiagnostic::error(
            REF_MISSING_ASSET,
            format!("asset {id} is listed in {ASSET_INDEX} but its file is missing"),
        )
        .in_file(ASSET_INDEX);
        findings.push(match text.find(&format!("\"{id}\"")) {
            Some(offset) => finding.at_offset(text, offset),
            None => finding,
        });
    }
}

/// A design folder (one holding `page.json` or `def.json`) without its
/// `nodes.json` has lost its nodes: the SVG beside it is a view, not the
/// record, and the load fails.
fn check_design_records(
    dir: &Path,
    files: &[(String, PathBuf)],
    findings: &mut Vec<SourceDiagnostic>,
) {
    for (name, _) in files {
        let Some(folder) = name
            .strip_suffix("/page.json")
            .or_else(|| name.strip_suffix("/def.json"))
        else {
            continue;
        };
        let records = format!("{folder}/{NODES_JSON}");
        // A legacy design keeps its nodes in an `.fnx` source, or in a
        // `nodes` folder before that.
        let legacy = fs::read_dir(dir.join(folder)).is_ok_and(|entries| {
            entries.flatten().any(|entry| {
                let path = entry.path();
                path.extension().is_some_and(|extension| extension == "fnx")
                    || path.file_name().is_some_and(|name| name == "nodes")
            })
        });
        if !legacy && !files.iter().any(|(other, _)| *other == records) {
            findings.push(
                SourceDiagnostic::error(
                    MANIFEST_FILE_MISSING,
                    format!(
                        "{records} is missing: it holds this design's nodes, and the SVG beside it cannot replace it"
                    ),
                )
                .in_file(records),
            );
        }
    }
}

/// Instances of components and paints of assets the project does not hold.
fn check_references(
    doc: &Doc,
    assets: &BTreeMap<AssetId, Vec<u8>>,
    svgs: &BTreeMap<String, String>,
    findings: &mut Vec<SourceDiagnostic>,
) -> Result<()> {
    let held: Vec<String> = assets.keys().map(json_key).collect::<Result<_>>()?;
    let mut pending: Vec<NodeId> = doc.scene.roots().to_vec();
    while let Some(id) = pending.pop() {
        pending.extend_from_slice(doc.scene.children_of(Some(id)));
        let Some(node) = doc.scene.get(id) else {
            continue;
        };
        let display = id.to_string();
        if let NodeData::Instance(instance) = &node.data
            && !doc.components.defs.contains_key(&instance.component)
        {
            findings.push(locate_node(
                SourceDiagnostic::error(
                    REF_MISSING_COMPONENT,
                    format!(
                        "{display}: \"{}\" is an instance of component {}, which the project does not define",
                        node.name, instance.component
                    ),
                )
                .for_node(&display),
                svgs,
            ));
        }
        let mut painted = Vec::new();
        image_assets(&serde_json::to_value(node)?, &mut painted);
        for asset in painted {
            if !held.contains(&asset) {
                findings.push(locate_node(
                    SourceDiagnostic::error(
                        REF_MISSING_ASSET,
                        format!(
                            "{display}: \"{}\" paints image asset {asset}, which the project does not hold",
                            node.name
                        ),
                    )
                    .for_node(&display),
                    svgs,
                ));
            }
        }
    }
    Ok(())
}

/// The `asset` of every image fill anywhere in a node's JSON, in the bare
/// serde spelling the records use.
fn image_assets(value: &Value, found: &mut Vec<String>) {
    match value {
        Value::Object(object) => {
            if object.get("kind").and_then(Value::as_str) == Some("image")
                && let Some(asset) = object.get("asset").and_then(Value::as_str)
            {
                found.push(asset.to_owned());
            }
            for child in object.values() {
                image_assets(child, found);
            }
        }
        Value::Array(items) => {
            for item in items {
                image_assets(item, found);
            }
        }
        _ => {}
    }
}

/// Compare the design files on disk with what the writer would emit for the
/// loaded document: a file it would write that is gone, and a node it would
/// draw that has no element. Deleting either by hand deletes nothing from
/// the project; the next save puts it back.
fn check_projection(
    dir: &Path,
    doc: &Doc,
    assets: &BTreeMap<AssetId, Vec<u8>>,
    svgs: &BTreeMap<String, String>,
    findings: &mut Vec<SourceDiagnostic>,
) -> Result<()> {
    let projection = web_project_files(doc, &asset_hrefs(assets), None, &[])?;
    for (path, bytes) in &projection.files {
        let name = path.to_string_lossy().replace('\\', "/");
        let design = name.starts_with(PAGES_DIR) || name.starts_with(COMPONENTS_DIR);
        if !design || !(name.ends_with(".svg") || name.ends_with(".css")) {
            continue;
        }
        if !dir.join(path).is_file() {
            findings.push(
                SourceDiagnostic::warning(
                    MANIFEST_FILE_MISSING,
                    format!(
                        "{name} is missing; the next save writes it again from nodes.json, without any hand edits it held"
                    ),
                )
                .in_file(name),
            );
            continue;
        }
        let Some(on_disk) = svgs.get(&name) else {
            continue;
        };
        let expected = String::from_utf8_lossy(bytes);
        for id in element_ids(&expected) {
            let Ok(node) = id.parse::<NodeId>() else {
                continue;
            };
            if on_disk.contains(&format!("id=\"{id}\"")) {
                continue;
            }
            let label = doc
                .scene
                .get(node)
                .map(|node| node.name.clone())
                .unwrap_or_default();
            findings.push(
                SourceDiagnostic::warning(
                    RECORD_NO_ELEMENT,
                    format!(
                        "{id}: \"{label}\" has no element in {name}; removing an element does not delete the node, and the next save draws it again"
                    ),
                )
                .for_node(id)
                .in_file(name.clone()),
            );
        }
    }
    Ok(())
}

/// Every `id="…"` value in emitted SVG text.
fn element_ids(svg: &str) -> impl Iterator<Item = &str> {
    svg.split("id=\"")
        .skip(1)
        .filter_map(|rest| rest.split('"').next())
}

/// Point a finding about a node at its element, in whichever design draws it.
fn locate_node(finding: SourceDiagnostic, svgs: &BTreeMap<String, String>) -> SourceDiagnostic {
    let Some(id) = finding.node_id.clone() else {
        return finding;
    };
    let needle = format!("id=\"{id}\"");
    for (name, text) in svgs {
        if let Some(offset) = text.find(&needle) {
            return finding.in_file(name.clone()).at_offset(text, offset);
        }
    }
    finding
}

#[cfg(test)]
mod tests {
    use super::*;

    fn codes(name: &str, text: &str) -> Vec<(&'static str, Option<u32>)> {
        let mut findings = Vec::new();
        check_file(name, text, &mut findings);
        findings
            .iter()
            .map(|finding| (finding.code, finding.line))
            .collect()
    }

    #[test]
    fn unbalanced_css_braces_are_found_outside_comments() {
        assert_eq!(codes("a.css", "#a { fill: red; }\n/* } { */\n"), vec![]);
        assert_eq!(
            codes("a.css", "#a { fill: red;\n#b { fill: blue; }\n"),
            vec![(PARSE_CSS, Some(1))]
        );
        assert_eq!(
            codes("a.css", "#a { fill: red; }\n}\n"),
            vec![(PARSE_CSS, Some(2))]
        );
    }

    #[test]
    fn a_truncated_svg_and_broken_json_are_errors_with_a_line() {
        assert_eq!(
            codes("a.svg", "<svg>\n  <g id=\"a\">\n"),
            vec![(PARSE_SVG, Some(3))]
        );
        assert_eq!(
            codes("a.json", "{\n  \"a\": 1,\n}\n"),
            vec![(PARSE_JSON, Some(3))]
        );
    }

    #[test]
    fn a_repeated_attribute_counts_its_first_id_only() {
        assert_eq!(
            codes("a.svg", "<svg><g id=\"a\" id=\"b\"/><g id=\"b\"/></svg>"),
            vec![]
        );
        assert_eq!(
            codes("a.svg", "<svg>\n<g x=\"1\" x=\"2\" id=\"a\"/>\n<g id=\"a\"/></svg>"),
            vec![(ID_DUPLICATE, Some(3))]
        );
    }

    #[test]
    fn a_tag_with_very_many_attributes_is_checked_in_linear_time() {
        let mut text = String::from("<svg><g id=\"a\"");
        for index in 0..200_000 {
            text.push_str(&format!(" a{index}=\"\""));
        }
        text.push_str("/><g id=\"a\"/></svg>");
        let started = std::time::Instant::now();
        let found = codes("a.svg", &text);
        let elapsed = started.elapsed();
        eprintln!("check_svg, 200000 attributes: {elapsed:?}");
        assert_eq!(found, vec![(ID_DUPLICATE, Some(1))]);
        // A duplicate check that compares every pair takes minutes here.
        assert!(elapsed < std::time::Duration::from_secs(10), "{elapsed:?}");
    }

    #[test]
    fn a_conflict_marker_wins_over_the_parse_error_it_causes() {
        assert_eq!(
            codes("a.json", "{\n<<<<<<< HEAD\n  \"a\": 1\n=======\n  \"a\": 2\n>>>>>>> x\n}\n"),
            vec![(PARSE_CONFLICT_MARKER, Some(2))]
        );
    }
}
